static const u8 RCON[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

static u8 gmul(u8 a, u8 b){ u8 p=0; int i; for(i=0;i<8;i++){ if(b&1) p^=a; b>>=1; a=(u8)((a<<1)^((a&0x80)?0x1b:0)); } return p; }
static void addrk(u8 s[16], const u8 *rk){ int i; for(i=0;i<16;i++) s[i]^=rk[i]; }
static void subbytes(u8 s[16]){ int i; for(i=0;i<16;i++) s[i]=SBOX[s[i]]; }
static u8 invsbox(u8 v){ int i; for(i=0;i<256;i++) if(SBOX[i]==v) return (u8)i; return 0; }

static void shiftrows(u8 s[16]){
    u8 t;
    t=s[1]; s[1]=s[5]; s[5]=s[9]; s[9]=s[13]; s[13]=t;
    t=s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t=s[15]; s[15]=s[11]; s[11]=s[7]; s[7]=s[3]; s[3]=t;
}
static void invshiftrows(u8 s[16]){
    u8 t;
    t=s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
    t=s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t=s[3]; s[3]=s[7]; s[7]=s[11]; s[11]=s[15]; s[15]=t;
}
static void mixcolumns(u8 s[16]){
    int i;
    for (i=0;i<16;i+=4){ u8 a=s[i],b=s[i+1],c=s[i+2],d=s[i+3];
        s[i]=(u8)(gmul(a,2)^gmul(b,3)^c^d);
        s[i+1]=(u8)(a^gmul(b,2)^gmul(c,3)^d);
        s[i+2]=(u8)(a^b^gmul(c,2)^gmul(d,3));
        s[i+3]=(u8)(gmul(a,3)^b^c^gmul(d,2)); }
}
